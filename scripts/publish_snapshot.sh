#!/usr/bin/env bash
# Publishes the COMPLETE served release (all markets, real data) to the always-on GitHub Pages site.
#
#   scripts/publish_snapshot.sh            # after a refresh (scripts/refresh.sh)
#
# 1. exports every API response as static files (py/agri/analysis/export_snapshot.py, ~4 min)
# 2. uploads them as one archive to the GitHub Release "data-snapshot" (replacing the previous one),
#    so the data never bloats the Git history
# 3. re-runs the Pages workflow, which unpacks the archive into the site.
# The app on Pages then reads it in snapshot mode; the data date shown is the release's data_as_of.
set -euo pipefail
cd "$(dirname "$0")/.."
REPO="${AGRI_PAGES_REPO:-kaushalrog/AG-DATA}"; BRANCH="${AGRI_PAGES_BRANCH:-agdata-2.0}"; TAG=data-snapshot
PYTHONPATH=py .venv/bin/python -m agri.analysis.export_snapshot --out build/snapshot
tar -C build/snapshot -czf build/snapshot.tar.gz .
VERSION="$(python3 -c 'import json;print(json.load(open("build/snapshot/current.json"))["version"])')"
NOTES="Static export of the served release ${VERSION} for the GitHub Pages site (generated by scripts/publish_snapshot.sh). Data: AGMARKNET via data.gov.in, GODL-India."
if gh release view "$TAG" -R "$REPO" >/dev/null 2>&1; then
  gh release upload "$TAG" build/snapshot.tar.gz -R "$REPO" --clobber
  gh release edit "$TAG" -R "$REPO" --notes "$NOTES" >/dev/null
else
  gh release create "$TAG" build/snapshot.tar.gz -R "$REPO" --target "$BRANCH" --prerelease \
    --title "Published data snapshot" --notes "$NOTES"
fi
gh workflow run pages.yml -R "$REPO" --ref "$BRANCH"
echo "uploaded ${VERSION}; the Pages workflow is deploying it (gh run watch -R $REPO)"
